// macOS virtual keycode（CGEventGetIntegerValueField 的 kCGKeyboardEventKeycode）
// 到 USB HID usage ID（usage page 0x07）的转换表。
//
// 数据源：Events.h（kVK_*）与 USB HID Usage Tables 10.5。
// 只收录常见键（ANSI 布局为主，外加 ISO/JIS 少数常用键）；
// 查不到的 keycode（Fn、音量键、电源键、小键盘 = 等）返回 ok=false，
// 回调会原样放过对应事件。
//
// vkTable 下标即 macOS virtual keycode（0x00-0x7E），值 0 表示"无映射"
// （HID usage 0 为保留值，不是合法按键，不会与真实映射混淆）；
// 字母区因 ANSI 键序与字母序不一致，单独放在 vkLetters。
var vkTable = [0x7F]uint32{
	// 0x0A 在 ISO 键盘是 §（Non-US \ and |，HID 0x64）；ANSI 键盘无此键。
	0x0A: 0x64,

	// 数字行与符号：HID 0x1E-0x38
	0x12: 0x1E, // 1
	0x13: 0x1F, // 2
	0x14: 0x20, // 3
	0x15: 0x21, // 4
	0x17: 0x22, // 5
	0x16: 0x23, // 6
	0x1A: 0x24, // 7
	0x1C: 0x25, // 8
	0x19: 0x26, // 9
	0x1D: 0x27, // 0
	0x1B: 0x2D, // -
	0x18: 0x2E, // =
	0x21: 0x2F, // [
	0x1E: 0x30, // ]
	0x2A: 0x31, // \ (ANSI)
	0x29: 0x33, // ;
	0x27: 0x34, // '
	0x32: 0x35, // `
	0x2B: 0x36, // ,
	0x2F: 0x37, // .
	0x2C: 0x38, // /

	// 主控制键
	0x24: 0x28, // Return
	0x30: 0x2B, // Tab
	0x31: 0x2C, // Space
	0x33: 0x2A, // Delete（退格）
	0x35: 0x29, // Escape
	0x39: 0x39, // CapsLock

	// 修饰键（左右分列，HID 0xE0-0xE7）
	0x36: 0xE7, // Right Command
	0x37: 0xE3, // Left Command
	0x38: 0xE1, // Left Shift
	0x3A: 0xE2, // Left Option
	0x3B: 0xE0, // Left Control
	0x3C: 0xE5, // Right Shift
	0x3D: 0xE6, // Right Option
	0x3E: 0xE4, // Right Control

	// 功能键 F1-F12（macOS 的 kVK 顺序是乱的，HID 是顺的）
	0x7A: 0x3A, // F1
	0x78: 0x3B, // F2
	0x63: 0x3C, // F3
	0x76: 0x3D, // F4
	0x60: 0x3E, // F5
	0x61: 0x3F, // F6
	0x62: 0x40, // F7
	0x64: 0x41, // F8
	0x65: 0x42, // F9
	0x6D: 0x43, // F10
	0x67: 0x44, // F11
	0x6F: 0x45, // F12
	// F13-F20（部分外接键盘有）
	0x69: 0x68, // F13
	0x6B: 0x69, // F14
	0x71: 0x6A, // F15
	0x6A: 0x6B, // F16
	0x40: 0x6C, // F17
	0x4F: 0x6D, // F18
	0x50: 0x6E, // F19
	0x5A: 0x6F, // F20

	// 编辑/导航键
	0x72: 0x49, // Insert（Help）
	0x73: 0x4A, // Home
	0x74: 0x4B, // Page Up
	0x75: 0x4C, // Delete Forward
	0x77: 0x4D, // End
	0x79: 0x4E, // Page Down
	0x7B: 0x50, // Left Arrow
	0x7C: 0x4F, // Right Arrow
	0x7D: 0x51, // Down Arrow
	0x7E: 0x52, // Up Arrow

	// 小键盘
	0x47: 0x53, // Clear（对应 HID NumLock）
	0x4B: 0x54, // /
	0x43: 0x55, // *
	0x4E: 0x56, // -
	0x45: 0x57, // +
	0x4C: 0x58, // Enter
	0x53: 0x59, // 1
	0x54: 0x5A, // 2
	0x55: 0x5B, // 3
	0x56: 0x5C, // 4
	0x57: 0x5D, // 5
	0x58: 0x5E, // 6
	0x59: 0x5F, // 7
	0x5B: 0x60, // 8
	0x5C: 0x61, // 9
	0x52: 0x62, // 0
	0x41: 0x63, // .

	// JIS 常见键
	0x68: 0x88, // かな（Kana，HID International2）
	0x5F: 0x85, // 小键盘逗号（HID Keypad Comma）
}

// 字母区 A-Z：kVK_ANSI_A=0x00, S=0x01, D=0x02, F=0x03, H=0x04, G=0x05,
// Z=0x06, X=0x07, C=0x08, V=0x09, B=0x0B, Q=0x0C, W=0x0D, E=0x0E,
// R=0x0F, Y=0x10, T=0x11, O=0x1F, U=0x20, I=0x22, P=0x23, L=0x25,
// J=0x26, K=0x28, N=0x2D, M=0x2E
// HID：A=0x04, B=0x05, ..., Z=0x1D（字母序）。
var vkLetters = map[uint32]uint32{
	0x00: 0x04, // A
	0x0B: 0x05, // B
	0x08: 0x06, // C
	0x02: 0x07, // D
	0x0E: 0x08, // E
	0x03: 0x09, // F
	0x05: 0x0A, // G
	0x04: 0x0B, // H
	0x22: 0x0C, // I
	0x26: 0x0D, // J
	0x28: 0x0E, // K
	0x25: 0x0F, // L
	0x2E: 0x10, // M
	0x2D: 0x11, // N
	0x1F: 0x12, // O
	0x23: 0x13, // P
	0x0C: 0x14, // Q
	0x0F: 0x15, // R
	0x01: 0x16, // S
	0x11: 0x17, // T
	0x20: 0x18, // U
	0x09: 0x19, // V
	0x0D: 0x1A, // W
	0x07: 0x1B, // X
	0x10: 0x1C, // Y
	0x06: 0x1D, // Z
}

// HIDForVK 把 macOS virtual keycode 转成 USB HID usage ID。
// ok=false 表示该 keycode 没有可靠映射（Fn、音量键、电源键、
// 小键盘 = 等），调用方应原样放过对应事件。
func HIDForVK(vk uint32) (hid uint32, ok bool) {
	if vk < uint32(len(vkTable)) {
		if hid = vkTable[vk]; hid != 0 {
			return hid, true
		}
	}
	hid, ok = vkLetters[vk]
	return hid, ok
}
